"""Compile query*.sql into one Python driver, and decompile it back.

Lets the single-shot NaiveLLM rewriter treat a query workload as one Python
file. Shape mirrors ADCo's pycompiler/pydecompiler.
"""

import argparse
import ast
import glob
import os
import re
import shutil


def parse_query_num(filename: str) -> int:
    match = re.search(r"query(\d+)\.sql$", filename)
    if not match:
        raise ValueError(f"Invalid query filename: {filename}")
    return int(match.group(1))


def compile_queries(input_dir: str, output_dir: str) -> None:
    sorted_files = []
    for path in glob.glob(os.path.join(input_dir, "query*.sql")):
        try:
            sorted_files.append((parse_query_num(path), path))
        except ValueError:
            continue
    sorted_files.sort()

    if not sorted_files:
        print(f"No query*.sql files found in {input_dir}")
        return

    os.makedirs(output_dir, exist_ok=True)

    # schema.sql rides along as read-only context for the rewriter.
    schema_src = os.path.join(input_dir, "schema.sql")
    if os.path.isfile(schema_src):
        shutil.copyfile(schema_src, os.path.join(output_dir, "schema.sql"))

    lines = [
        '"""',
        "Database application for query workload.",
        "Auto-generated by query_codec. Do not edit manually.",
        '"""',
        "",
        "import logging",
        "import os",
        "import sys",
        "",
        "import psycopg2",
        "from psycopg2.extras import RealDictCursor",
        "",
        "logging.basicConfig(",
        "    level=logging.INFO,",
        '    format="%(asctime)s [%(levelname)s] %(name)s: %(message)s",',
        ")",
        "logger = logging.getLogger(__name__)",
        "",
        "",
        "class DatabaseClient:",
        "    def __init__(self):",
        "        self._conn = None",
        "",
        "    def connect(self):",
        "        self._conn = psycopg2.connect(",
        '            host=os.environ.get("DB_HOST", "localhost"),',
        '            port=int(os.environ.get("DB_PORT", 5432)),',
        '            dbname=os.environ.get("DB_NAME", "stats"),',
        '            user=os.environ.get("DB_USER", "postgres"),',
        '            password=os.environ.get("DB_PASSWORD", ""),',
        "        )",
        '        logger.info("Connected to database")',
        "",
        "    def close(self):",
        "        if self._conn:",
        "            self._conn.close()",
        "",
        "    def __enter__(self):",
        "        self.connect()",
        "        return self",
        "",
        "    def __exit__(self, *_):",
        "        self.close()",
        "",
    ]

    for num, path in sorted_files:
        with open(path, "r", encoding="utf-8") as f:
            sql_content = f.read().strip()

        lines.append(f"    # --- query{num} ---")
        lines.append(f'    QUERY_{num} = """\\')
        lines.append(sql_content)
        lines.append('"""')
        lines.append(f"    # [END query{num}]")
        lines.append("")

        lines.append(f"    def run_query{num}(self):")
        lines.append(f'        logger.info("Executing query{num}")')
        lines.append("        with self._conn.cursor(cursor_factory=RealDictCursor) as cur:")
        lines.append(f"            cur.execute(self.QUERY_{num})")
        lines.append("            results = cur.fetchall()")
        lines.append(f'            logger.info("query{num} returned %d row(s)", len(results))')
        lines.append("            return results")
        lines.append("")

    lines.append("def main():")
    lines.append("    with DatabaseClient() as client:")
    lines.append("        try:")
    for num, _ in sorted_files:
        lines.append(f"            print(client.run_query{num}())")
    lines.append("        except Exception as exc:")
    lines.append('            logger.error("Query failed: %s", exc)')
    lines.append("            sys.exit(1)")
    lines.append("")
    lines.append("")
    lines.append('if __name__ == "__main__":')
    lines.append("    main()")

    out_file = os.path.join(output_dir, "db_app.py")
    with open(out_file, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Successfully compiled {len(sorted_files)} queries to {out_file}")


def decompile_app(input_dir: str, output_dir: str) -> None:
    db_app_path = os.path.join(input_dir, "db_app.py")
    if not os.path.isfile(db_app_path):
        print(f"ERROR: db_app.py not found in {input_dir}")
        return

    with open(db_app_path, "r", encoding="utf-8") as f:
        content = f.read()

    try:
        tree = ast.parse(content)
    except SyntaxError as e:
        print(f"ERROR: Failed to parse db_app.py: {e}")
        return

    client_class = None
    for node in tree.body:
        if isinstance(node, ast.ClassDef) and node.name == "DatabaseClient":
            client_class = node
            break

    nodes_to_search = client_class.body if client_class else tree.body

    os.makedirs(output_dir, exist_ok=True)
    decompiled = 0

    for node in nodes_to_search:
        if not isinstance(node, ast.Assign):
            continue
        for target in node.targets:
            if not isinstance(target, ast.Name):
                continue
            match = re.match(r"^QUERY_(\d+)$", target.id)
            if not match:
                continue
            val = node.value
            if isinstance(val, ast.Constant) and isinstance(val.value, str):
                sql_text = val.value
            elif isinstance(val, ast.Str):  # Python < 3.8
                sql_text = val.s
            else:
                continue
            out_path = os.path.join(output_dir, f"query{match.group(1)}.sql")
            with open(out_path, "w", encoding="utf-8") as out_f:
                out_f.write(sql_text + "\n")
            decompiled += 1

    print(f"Successfully decompiled {decompiled} queries to {output_dir}")


def main() -> None:
    parser = argparse.ArgumentParser(description="Compile query*.sql into a Python driver, or decompile it back")
    sub = parser.add_subparsers(dest="op", required=True)
    for name in ("compile", "decompile"):
        p = sub.add_parser(name)
        p.add_argument("--input-dir", required=True)
        p.add_argument("--output-dir", required=True)
    args = parser.parse_args()

    if args.op == "compile":
        compile_queries(args.input_dir, args.output_dir)
    else:
        decompile_app(args.input_dir, args.output_dir)


if __name__ == "__main__":
    main()
